CREATE TABLE IF NOT EXISTS curriculum_weekly_lessons (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    document_id BIGINT UNSIGNED NOT NULL,
    source_chunk_id BIGINT UNSIGNED NOT NULL,
    semester_number TINYINT UNSIGNED NULL,
    week_number TINYINT UNSIGNED NOT NULL,
    topic VARCHAR(500) NOT NULL,
    focal_areas JSON NOT NULL,
    assessment_mode VARCHAR(500) NULL,
    source_page INT UNSIGNED NULL,
    ai_generated TINYINT(1) NOT NULL DEFAULT 1,
    model_used VARCHAR(120) NULL,
    review_status ENUM('unreviewed', 'verified', 'rejected') NOT NULL DEFAULT 'unreviewed',
    review_notes TEXT NULL,
    verified_by BIGINT UNSIGNED NULL,
    verified_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_curriculum_weekly_lesson (document_id, source_chunk_id, semester_number, week_number, topic(100)),
    KEY idx_curriculum_weekly_lookup (review_status, semester_number, week_number),
    CONSTRAINT fk_curriculum_weekly_document FOREIGN KEY (document_id) REFERENCES curriculum_documents(id) ON DELETE CASCADE,
    CONSTRAINT fk_curriculum_weekly_chunk FOREIGN KEY (source_chunk_id) REFERENCES curriculum_chunks(id) ON DELETE CASCADE,
    CONSTRAINT fk_curriculum_weekly_verifier FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
